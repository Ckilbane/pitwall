#!/usr/bin/env python3
"""Generate site/css/tokens.css from docs/design/tokens.json.

Usage: python3 site/tools/build_tokens.py docs/design/tokens.json site/css/tokens.css
(both arguments optional; defaults are relative to the repo root).

Output: a light :root block, a [data-theme="dark"] block, and the same dark block under
prefers-color-scheme for visitors who have not chosen a theme. Every colour token appears in
every block. Deterministic.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FONT_VAR = {"display": "--font-display", "sans": "--font-sans", "serif": "--font-serif", "mono": "--font-mono"}


def type_decls(name, spec):
    """'600 11px/14px sans, uppercase, 0.08em' -> shorthand var + extra vars."""
    head, *extras = [p.strip() for p in spec.split(",")]
    m = re.match(r"^(italic\s+)?(\d{3})\s+(\d+px/\d+px)\s+(display|sans|serif|mono)$", head)
    if not m:
        raise SystemExit(f"unparseable type token {name}: {spec}")
    style, weight, size, fam = m.groups()
    out = [f"--type-{name}: {(style or '')}{weight} {size} var({FONT_VAR[fam]});"]
    for ex in extras:
        if ex == "uppercase":
            out.append(f"--type-{name}-transform: uppercase;")
        elif ex == "tabular":
            out.append(f"--type-{name}-numeric: tabular-nums;")
        elif re.match(r"^[\d.]+em$", ex):
            out.append(f"--type-{name}-tracking: {ex};")
        else:
            raise SystemExit(f"unknown type modifier {ex!r} in {name}")
    return out


def build(tokens):
    color, shadow = tokens["color"], tokens["shadow"]

    def theme_vars(mode):
        lines = [f"  --{k}: {v[mode]};" for k, v in color.items()]
        lines += [f"  --{k}: {v[mode]};" for k, v in shadow.items()]
        return lines

    common = []
    common += [f"  --font-{k}: {v};" for k, v in tokens["fonts"].items()]
    common += [f"  --{k}: {v};" for k, v in tokens["space"].items()]
    common += [f"  --{k}: {v};" for k, v in tokens["radius"].items()]
    common += [f"  --{k}: {v};" for k, v in tokens["stroke"].items()]
    for name, spec in tokens["type"].items():
        common += ["  " + d for d in type_decls(name, spec)]

    out = ["/* Generated by site/tools/build_tokens.py from docs/design/tokens.json. Do not edit. */",
           ":root {", "  color-scheme: light;"]
    out += theme_vars("light") + common + ["}", ""]
    dark = theme_vars("dark")
    out += ['\n:root[data-theme="dark"] {', "  color-scheme: dark;"] + dark + ["}", ""]
    out += ["@media (prefers-color-scheme: dark) {", "  :root:not([data-theme=\"light\"]) {", "    color-scheme: dark;"]
    out += ["  " + d for d in dark] + ["  }", "}", ""]
    return "\n".join(out).replace("\n\n\n", "\n\n")


def main(argv):
    src = Path(argv[1]) if len(argv) > 1 else ROOT / "docs/design/tokens.json"
    dst = Path(argv[2]) if len(argv) > 2 else ROOT / "site/css/tokens.css"
    tokens = json.loads(src.read_text())
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(build(tokens))
    print(f"wrote {dst}")


if __name__ == "__main__":
    main(sys.argv)
